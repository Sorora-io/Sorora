import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
await db.exec(`create role authenticated;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$select '00000000-0000-0000-0000-000000000001'::uuid$$;
grant usage on schema auth to authenticated;
create table memberships(user_id uuid, role text, status text, is_admin boolean default false, requested_role text);
alter table memberships enable row level security;
grant insert on memberships to authenticated;`);
const sql = await readFile(new URL('../migrations/0035_join_as_member_only.sql', import.meta.url), 'utf8');
await db.exec(sql); await db.exec(sql);
await db.exec('set role authenticated');
const insert = (role, admin = false, requested = null, user = '00000000-0000-0000-0000-000000000001', status = 'pending') => db.query('insert into memberships values($1,$2,$3,$4,$5)', [user,role,status,admin,requested]);
await insert('big'); await insert('little');
await assert.rejects(() => insert('admin'), /row-level security/);
await assert.rejects(() => insert('big', true), /row-level security/);
await assert.rejects(() => insert('big', false, 'admin'), /row-level security/);
await assert.rejects(() => insert('big', false, null, '00000000-0000-0000-0000-000000000002'), /row-level security/);
await assert.rejects(() => insert('big', false, null, undefined, 'approved'), /row-level security/);
await db.exec('reset role');
await insert('admin', true, null, undefined, 'approved');
console.log('Join policy: Big/Little allowed; admin access, role requests, other users, and pre-approved joins rejected; privileged creator path preserved.');
await db.close();
